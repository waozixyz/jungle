"""Compile the ABC game's letter tables from the Picture Book catalog.

Every optional example uses words that already exist in
tools/book_catalog.py with its watercolor art and narration, so the alphabet
never drifts from the book. Run from the repository root: python3 tools/abc_catalog.py
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))
import book_catalog as cat  # noqa: E402

MAX_WORDS_PER_LETTER = 6

EN_NAMES = [
    "ay", "bee", "see", "dee", "ee", "ef", "gee", "aitch", "eye", "jay", "kay",
    "el", "em", "en", "oh", "pee", "cue", "ar", "ess", "tee", "you", "vee",
    "double you", "ex", "why", "zed",
]
EXTRA_LETTERS = {"de": ["Ä", "Ö", "Ü", "ß"], "es": ["Ñ"]}
EXTRA_NAMES = {"de": ["ä", "ö", "ü", "Eszett"], "es": ["eñe"]}


def alphabet(language):
    letters = list("ABCDEFGHIJKLMNOPQRSTUVWXYZ")
    if language == "es":
        letters.insert(14, "Ñ")
    elif language == "de":
        letters += EXTRA_LETTERS[language]
    return letters


def letter_names(language):
    if language == "en":
        return EN_NAMES
    return [cat.LETTERS[language][letter.lower()] for letter in alphabet(language)]


def build_language(language):
    """Map every catalog word to the letter it starts with in this language."""
    index = cat.LANGUAGES.index(language)
    by_letter = {}
    for order, name in enumerate(cat.NAMES):
        word = cat.WORDS[name][index]
        by_letter.setdefault(word[0].upper(), []).append((len(word), order, name))
    pages = []
    for letter in alphabet(language):
        words = sorted(by_letter.get(letter, []), key=lambda entry: entry[:2])
        pages.append([name for _, _, name in words[:MAX_WORDS_PER_LETTER]])
    return pages


def duration(name, language, simple):
    path = ROOT / cat.voice_path(name, language, simple)
    return json.loads(path.with_suffix(".speech.json").read_text())["duration"]


def table(name, values, kind):
    output = ""
    for start in range(0, len(values), 48):
        chunk = values[start:start + 48]
        output += f"{name}_{start}: [{len(chunk)}]{kind} = .[\n"
        if kind == "string":
            output += "".join(f"    {json.dumps(v, ensure_ascii=False)},\n" for v in chunk)
        elif kind == "float64":
            output += "".join(f"    {v:.6f},\n" for v in chunk)
        else:
            output += "".join(f"    {v},\n" for v in chunk)
        output += "];\n"
    return output


def single_table(name, values):
    return f"{name}: [{len(values)}]string = .[{', '.join(json.dumps(v, ensure_ascii=False) for v in values)}];\n"


def accessor(function, base, count, result, default):
    output = f"{function} :: (at: s32) -> {result} {{\n"
    for start in range(0, count, 48):
        output += f"    if at < {min(start + 48, count)} {{ return {base}_{start}[at - {start}] }}\n"
    return output + f"    return {default}\n}}\n"


def main():
    names = list(cat.NAMES)
    position = {name: at for at, name in enumerate(names)}
    out = ["// Generated by tools/abc_catalog.py from the Picture Book catalog.\n"]
    out.append(f"WORD_COUNT :: {len(names)}\n")

    art = [f"assets/jungle-book/items/{name}.png" for name in names]
    out.append(table("word_art", art, "string"))
    out.append(accessor("WordArt", "word_art", len(art), "string", '""'))
    scenes = [f"assets/jungle-book/pages/{name}.jpg" for name in names]
    out.append(table("word_scene", scenes, "string"))
    out.append(accessor("WordScene", "word_scene", len(scenes), "string", '""'))

    for index, language in enumerate(cat.LANGUAGES):
        words = [cat.WORDS[name][index] for name in names]
        out.append(table(f"word_name_{language}", words, "string"))
        out.append(accessor(f"WordName_{language}", f"word_name_{language}", len(words), "string", '""'))
        for mode in ("simple", "spelling"):
            paths = [cat.voice_path(name, language, mode == "simple") for name in names]
            seconds = [duration(name, language, mode == "simple") for name in names]
            out.append(table(f"word_voice_{language}_{mode}", paths, "string"))
            out.append(accessor(f"WordVoice_{language}_{mode}", f"word_voice_{language}_{mode}", len(paths), "string", '""'))
            out.append(table(f"word_seconds_{language}_{mode}", seconds, "float64"))
            out.append(accessor(f"WordSeconds_{language}_{mode}", f"word_seconds_{language}_{mode}", len(seconds), "float64", "0.0"))

    for language in cat.LANGUAGES:
        letters = alphabet(language)
        pages = build_language(language)
        out.append(f"LETTER_COUNT_{language.upper()} :: {len(letters)}\n")
        out.append(single_table(f"alphabet_{language}", letters))
        out.append(single_table(f"alphabet_lower_{language}",
                                [letter if letter == "ß" else letter.lower() for letter in letters]))
        out.append(single_table(f"letter_name_{language}", letter_names(language)))
        paths = [f"assets/abc/sounds/{language}/letters/{ord(letter.lower()):04x}.wav" for letter in letters]
        out.append(single_table(f"letter_voice_{language}", paths))
        flat = [position[name] for page in pages for name in page]
        starts = [0]
        for page in pages:
            starts.append(starts[-1] + len(page))
        out.append(f"letter_starts_{language}: [{len(starts)}]s32 = .[{', '.join(str(s) for s in starts)}];\n")
        out.append(table(f"letter_words_{language}", flat, "s32"))
        words_accessor = f"LetterWord_{language} :: (at: s32) -> s32 {{\n"
        for start in range(0, len(flat), 48):
            words_accessor += f"    if at < {min(start + 48, len(flat))} {{ return letter_words_{language}_{start}[at - {start}] }}\n"
        out.append(words_accessor + "    return 0\n}\n")
        gaps = [letter for letter, page in zip(letters, pages) if not page]
        print(f"{language}: {len(letters) - len(gaps)} letters with words, gaps: {' '.join(gaps) or 'none'}")

    out.append("""LetterWordCount :: (language: s32, letter: s32) -> s32 {
    starts := LetterStarts(language)
    if letter < 0 || letter >= LetterCount(language) { return 0 }
    return starts[letter + 1] - starts[letter]
}

LetterCount :: (language: s32) -> s32 {
    if language == 1 { return LETTER_COUNT_DE }
    if language == 2 { return LETTER_COUNT_ES }
    return LETTER_COUNT_EN
}

LetterStarts :: (language: s32) -> []s32 {
    if language == 1 { return letter_starts_de[:] }
    if language == 2 { return letter_starts_es[:] }
    return letter_starts_en[:]
}

LetterWord :: (language: s32, letter: s32, at: s32) -> s32 {
    starts := LetterStarts(language)
    if language == 1 { return LetterWord_de(starts[letter] + at) }
    if language == 2 { return LetterWord_es(starts[letter] + at) }
    return LetterWord_en(starts[letter] + at)
}

LetterText :: (language: s32, letter: s32) -> string {
    if language == 1 { return alphabet_de[letter] }
    if language == 2 { return alphabet_es[letter] }
    return alphabet_en[letter]
}

LetterLower :: (language: s32, letter: s32) -> string {
    if language == 1 { return alphabet_lower_de[letter] }
    if language == 2 { return alphabet_lower_es[letter] }
    return alphabet_lower_en[letter]
}

LetterVoice :: (language: s32, letter: s32) -> string {
    if language == 1 { return letter_voice_de[letter] }
    if language == 2 { return letter_voice_es[letter] }
    return letter_voice_en[letter]
}

LetterName :: (language: s32, letter: s32) -> string {
    if language == 1 { return letter_name_de[letter] }
    if language == 2 { return letter_name_es[letter] }
    return letter_name_en[letter]
}
""")
    (ROOT / "games/abc/abc_data.zi").write_text("".join(out), encoding="utf-8")
    print(f"Wrote games/abc/abc_data.zi with {len(names)} words")


if __name__ == "__main__":
    main()

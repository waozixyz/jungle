"""Prepare the Picture Book's covers, word lists and narration timings.

Each page is one whole watercolor scene in assets/jungle-book/pages, and
each word also has a transparent cut-out in assets/jungle-book/items for
Animal Counting and the ABC Book. Both are drawn with Codex image generation
in the title-screen cover style (see AGENTS.md).
"""
from pathlib import Path
import json
from math import ceil
import sys
from PIL import Image
from book_catalog import BOOKS, BOOK_GROUPS, NAMES, PAGE_NAMES, PENDING_MEDIA, WORDS, LANGUAGES, narration, voice_path, TITLES

ROOT = Path(__file__).resolve().parents[1]
SCENES = ROOT / "assets/jungle-book/pages"


def main():
    catalog_only = "--catalog-only" in sys.argv
    # While new art and speech are being made, only those exact subjects may be absent.
    pending = set(PENDING_MEDIA) if "--pending-media" in sys.argv else set()
    assert catalog_only or not pending, "--pending-media only regenerates the catalog sources"
    previews = ROOT / "assets/jungle-book/previews"
    missing = [name for name in NAMES if name not in pending and not (SCENES / (name + ".jpg")).exists()]
    assert not missing, "pages without a scene: " + ", ".join(missing)
    starts = []
    index = 0
    for category, names in BOOKS:
        starts.append(index)
        index += len(names)
    if not catalog_only:
        previews.mkdir(parents=True, exist_ok=True)
        # A book's cover is its first page.
        for category, names in BOOKS:
            with Image.open(SCENES / (names[0] + ".jpg")) as cover:
                cover.convert("RGB").resize((768, 768), Image.Resampling.LANCZOS).save(previews / (category + ".jpg"), quality=86)
        with Image.open(SCENES / (NAMES[0] + ".jpg")) as first:
            first.convert("RGB").resize((64, 64), Image.Resampling.LANCZOS).save(ROOT / "assets/jungle/book.png", optimize=True)
        sheet = Image.new("RGB", (840, 210 * ceil(len(NAMES) / 4)), "#fcf2d4")
        for at, name in enumerate(NAMES):
            with Image.open(SCENES / (name + ".jpg")) as page:
                sheet.paste(page.convert("RGB").resize((210, 210), Image.Resampling.LANCZOS), (at % 4 * 210, at // 4 * 210))
        sheet.save(ROOT / "art/generated/picture-book-preview.png", optimize=True)
    counts = ", ".join(str(len(names)) for _, names in BOOKS)
    catalog = "// Generated by tools/book_art.py from the illustrated books.\n"
    catalog += f"CATEGORY_COUNT :: {len(BOOKS)}\n"
    catalog += f"category_ids: [{len(BOOKS)}]string = .[" + ", ".join(json.dumps(c) for c, _ in BOOKS) + "];\n"
    catalog += f"category_counts: [{len(BOOKS)}]s32 = .{{{counts}}};\n"
    catalog += f"category_starts: [{len(BOOKS)}]s32 = .[" + ", ".join(map(str, starts)) + "];\n"
    groups = BOOK_GROUPS
    order = [category for _, members in groups for category in members]
    assert len(order) == len(set(order)) == len(BOOKS) and set(order) == set(dict(BOOKS))
    catalog += f"shelf_order: [{len(BOOKS)}]s32 = .[" + ", ".join(str([c for c, _ in BOOKS].index(c)) for c in order) + "];\n"
    catalog += f'book_groups: [{len(groups)}]string = .[' + ','.join(json.dumps(name) for name, _ in groups) + '];\n'
    group_counts = [len(members) for _, members in groups]
    group_starts = [sum(group_counts[:index]) for index in range(len(groups))]
    catalog += f'group_starts: [{len(groups)}]s32 = .[' + ','.join(map(str, group_starts)) + '];\n'
    catalog += f'group_counts: [{len(groups)}]s32 = .[' + ','.join(map(str, group_counts)) + '];\n'
    catalog += f'category_groups: [{len(BOOKS)}]s32 = .[' + ','.join(str(next(i for i,(_,members) in enumerate(groups) if c in members)) for c,_ in BOOKS) + '];\n'
    catalog += f"category_names: [{len(BOOKS)}]string = .[" + ", ".join(json.dumps(TITLES[c][0]) for c, _ in BOOKS) + "];\n"
    catalog += f"category_previews: [{len(BOOKS)}]string = .[" + ", ".join(json.dumps("assets/jungle-book/previews/" + c + ".jpg") for c, _ in BOOKS) + "];\n"
    catalog += string_table("page_paths", [f"assets/jungle-book/pages/{name}.jpg" for name in PAGE_NAMES])
    for language_index, language in enumerate(LANGUAGES):
        catalog += string_table(f"page_names_{language}", [WORDS[name][language_index] for name in PAGE_NAMES])
        catalog += string_table(f"page_spelling_{language}", [" ".join(WORDS[name][language_index].upper()) for name in PAGE_NAMES])
    (ROOT / "games/book/book_pages.zi").write_text(catalog)
    voices = "// Generated from verified, measured recordings by tools/book_art.py.\n"
    for language in LANGUAGES:
        for simple in (False, True):
            suffix = language + ("_simple" if simple else "_spelling")
            paths = [voice_path(name, language, simple) for name in PAGE_NAMES]
            durations = []
            for name, path in zip(PAGE_NAMES, paths):
                receipt_path = (ROOT / path).with_suffix(".speech.json")
                if name in pending and not receipt_path.exists():
                    durations.append(0.0)
                    continue
                receipt = json.loads(receipt_path.read_text())
                assert receipt["text"] == narration(name, language, simple), (name, language, simple)
                durations.append(receipt["duration"])
            for start in range(0, len(paths), 48):
                chunk = paths[start:start+48]
                voices += f"voice_paths_{suffix}_{start}: [{len(chunk)}]string = .[\n"
                voices += "".join(f'    "{path}",\n' for path in chunk) + "];\n"
            voices += f"VoicePath_{suffix} :: (at: s32) -> string {{\n"
            for start in range(0, len(paths), 48):
                voices += f"    if at < {min(start+48,len(paths))} {{ return voice_paths_{suffix}_{start}[at - {start}] }}\n"
            voices += '    return ""\n}\n'
            for start in range(0, len(durations), 48):
                chunk = durations[start:start+48]
                voices += f"voice_seconds_{suffix}_{start}: [{len(chunk)}]float64 = .[\n" + "".join(f"    {duration:.6f},\n" for duration in chunk) + "];\n"
            voices += f"VoiceSeconds_{suffix} :: (at: s32) -> float64 {{\n"
            for start in range(0, len(durations), 48):
                voices += f"    if at < {min(start+48,len(durations))} {{ return voice_seconds_{suffix}_{start}[at - {start}] }}\n"
            voices += "    return 0.0\n}\n"
    (ROOT / "games/book/book_voice.zi").write_text(voices)
    print(f"Prepared {len(NAMES)} scene pages, book covers, word lists and narration timings")


def string_table(name, values):
    output = ""
    for start in range(0, len(values), 48):
        chunk = values[start:start+48]
        output += f"{name}_{start}: [{len(chunk)}]string = .[\n"
        output += "".join("    " + json.dumps(value, ensure_ascii=False) + ",\n" for value in chunk) + "];\n"
    output += f"{name} :: (at: s32) -> string {{\n"
    for start in range(0, len(values), 48):
        output += f"    if at < {min(start+48,len(values))} {{ return {name}_{start}[at - {start}] }}\n"
    return output + '    return ""\n}\n'


if __name__ == "__main__":
    main()

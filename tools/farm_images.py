"""Farm's exact runtime inventory, trimmed anchors and reproducible exports.

--write preserves originals privately, exports exact lossless cut-outs and
regenerates garden_art.zi. --check needs only tracked files (also in CI).
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import shutil

from PIL import Image
from image_exports import ROOT, trim_cutout, check_cutout, export_image

DATA = ROOT/'tools/farm_images.json'
GENERATED = ROOT/'games/garden/garden_art.zi'
LOCAL = ROOT/'local/art-development/farm-asset-trim'
CROPS = ('sunflower','tomato','carrot','strawberry','pumpkin','cabbage','beans','corn','cucumber')
# Largest logical canvas in jungle_garden.zi; the runtime caps retro.scale at 1.8.
LOGICAL = {**dict.fromkeys(CROPS,76), **dict.fromkeys(('seed-'+c for c in CROPS),102),
           'sprout':68,'watering-can':76,'harvest-basket':66,'seed-pouch':58,
           'compost-bag':96,'sprinkler':96,'market-stall':60,'hand-cupped':70,
           'goji':68,'soil-mound':68,'soil-mound-wet':68,
           'campus-arrow':240,'campus-arrow-glow':240,'market-arrow':170,'market-arrow-glow':170}
CURSORS = {'cursor-watering-can':(2,14), 'cursor-harvest-basket':(16,16)}
SCENES = {f'assets/garden/{folder}/{prefix}-{orientation}.avif'
          for folder,prefix in (('art','scene'),('play','garden'))
          for orientation in ('landscape','portrait')}
FIELDS = {f'assets/garden/art/field-{orientation}-{i}.avif'
          for orientation in ('landscape','portrait') for i in range(4)}
PLAY = {f'assets/garden/play/{name}.avif' for name in LOGICAL.keys() | CURSORS.keys()}
RUNTIME = SCENES | FIELDS | PLAY


def digest(path):
    with Path(path).open('rb') as stream:
        return hashlib.file_digest(stream,'sha256').hexdigest()


def generated(rows):
    lines = ['// Generated by tools/farm_images.py; original-canvas anchors survive trimming.',
             'FarmArtRect :: struct { width: s32; height: s32; x: s32; y: s32; w: s32; h: s32 }',
             'FarmArt :: (name: string) -> FarmArtRect {']
    for name,row in sorted(rows.items()):
        if name in CURSORS: continue
        ow,oh=row['original_size']; x,y,r,b=row['crop']
        lines.append(f'    if name=="{name}" {{ return .{{{ow},{oh},{x},{y},{r-x},{b-y}}} }}')
    lines += ['    return .{}','}','']
    return '\n'.join(lines)


def write():
    rows={}
    for name in sorted(LOGICAL.keys() | CURSORS.keys()):
        path=ROOT/f'assets/garden/play/{name}.avif'
        original=LOCAL/'original'/path.relative_to(ROOT)
        if not original.exists():
            original.parent.mkdir(parents=True,exist_ok=True)
            if name.startswith(('campus-arrow','market-arrow')):
                direction='right' if name.startswith('campus') else 'left'
                suffix='-glow' if name.endswith('-glow') else ''
                shutil.copyfile(ROOT/f'assets/jungle/title/objects/wood-arrow-{direction}{suffix}.avif',original)
            else: shutil.copyfile(path,original)
        display=32 if name in CURSORS else LOGICAL[name]*1.8
        with Image.open(original) as picture:
            size=picture.size
            result,box=trim_cutout(picture,display,align=4 if name in CURSORS else 1,
                                    alpha_floor=0 if name in CURSORS else 8)
        if name in CURSORS:
            # Downsampling can ring outside the original dark cursor outline.
            # Keep its established no-light-fringe/clear-border contract.
            pixels=result.load()
            for y in range(result.height):
                for x in range(result.width):
                    r,g,b,a=pixels[x,y]
                    light=.299*r+.587*g+.114*b
                    if a<=8: pixels[x,y]=(0,0,0,0)
                    elif a<200 and light>140:
                        pixels[x,y]=(int(r*138/light),int(g*138/light),int(b*138/light),a)
        master=LOCAL/'trimmed'/f'{name}.png';master.parent.mkdir(parents=True,exist_ok=True)
        result.save(master)
        export_image(master,path,'cutout')
        row={'original_size':list(size),'crop':list(box),'dimensions':list(result.size),
             'max_display':display,'sha256':digest(path),'bytes':path.stat().st_size,
             'master':str(original.relative_to(ROOT))}
        if name in CURSORS:
            row['cursor']=[(box[2]-box[0])//4,(box[3]-box[1])//4,
                           CURSORS[name][0]-box[0]//4,CURSORS[name][1]-box[1]//4]
        rows[name]=row
    DATA.write_text(json.dumps({'format':1,'cutouts':rows},indent=2)+'\n')
    GENERATED.write_text(generated(rows))
    for manifest in (ROOT/'tools/art_provenance').glob('four-gardens-*.json'):
        data=json.loads(manifest.read_text())
        for row in data['assets']:
            name=row['name']; path=ROOT/row['runtime']
            if name in rows:
                row.update({k:rows[name][k] for k in ('sha256','bytes','dimensions')})
                row['runtime_trim']='tools/farm_images.json'
            else:
                # Re-export the opaque painting from its preserved PNG master.
                export=export_image(ROOT/row['source'],path,'title-background')
                row.update(sha256=digest(path),bytes=path.stat().st_size,
                           quality=export.quality,lossless=export.lossless,export_role='title-background')
        manifest.write_text(json.dumps(data,ensure_ascii=False,indent=2)+'\n')


def check():
    rows=json.loads(DATA.read_text())['cutouts']
    source=(ROOT/'games/garden/jungle_garden.zi').read_text()
    assert rows.keys()==LOGICAL.keys() | CURSORS.keys(), 'Unreferenced/missing cut-out'
    assert GENERATED.read_text()==generated(rows), 'Run python3 tools/farm_images.py --write'
    actual={str(p.relative_to(ROOT)) for p in (ROOT/'assets/garden').rglob('*.avif')}
    assert actual==RUNTIME, ('Unreferenced/missing Farm image',actual ^ RUNTIME)
    for name,row in rows.items():
        path=ROOT/f'assets/garden/play/{name}.avif'
        ow,oh=row['original_size']; left,top,right,bottom=row['crop']
        assert 0<=left<right<=ow and 0<=top<bottom<=oh,name
        display=row['max_display']*max(right-left,bottom-top)/max(ow,oh)
        check_cutout(path,display)
        with Image.open(path) as picture:
            assert list(picture.size)==row['dimensions'],name
        assert digest(path)==row['sha256'],name
        if name in LOGICAL: assert row['max_display']==LOGICAL[name]*1.8,name
        else:
            assert row['max_display']==32 and row['dimensions']==[2*n for n in row['cursor'][:2]],name
            cursor=re.search(r'asset_path="assets/garden/play/'+re.escape(name)+r'\.avif",'
                             r'\.width=(\d+),\.height=(\d+),\.hotspot_x=(\d+),\.hotspot_y=(\d+)',source)
            assert cursor and list(map(int,cursor.groups()))==row['cursor'], ('Cursor anchor changed',name)
    # Packaging and every web backend use the same explicit runtime list.
    from shared_assets import GAMES, GameFiles, Folder
    # Besides its own pictures, the Farm ships the title's Campus return sign.
    signs=set(GAMES['jungle-garden'].get('extra',{}))
    assert set(GameFiles('jungle-garden'))==RUNTIME|signs, 'Farm packs must contain exactly runtime images'
    assert set(Folder('assets/garden'))==RUNTIME, 'Browser Farm sources must contain exactly runtime images'
    assert 'FarmArt(name)' in source and 'ImageFit.ImageFitStretch' in source
    for name in LOGICAL:
        assert f'"{name}"' in source or name.startswith(('seed-','campus-arrow','market-arrow','soil-mound')), ('Unreferenced art',name)
    print(f'local Farm image check: {len(RUNTIME)} referenced AVIFs, {len(rows)} tight lossless cut-outs, <=2x display and generated anchors passed')


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write',action='store_true')
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    if args.write: write()
    check()

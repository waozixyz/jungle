"""Compile the complete UI inventory into portable Ziran lookups."""
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]

def main():
    rows = json.loads((ROOT / 'locales/ui.json').read_text())
    out = '// Generated by tools/locales.py from locales/ui.json.\n#import "std/format"\n'
    out += 'language: s32;\nLanguageCode :: () -> string {\n    if language == 1 { return "de" }\n    if language == 2 { return "es" }\n    return "en"\n}\n'
    out += 'LanguageSet :: (code: string) {\n    language = ifx code == "de" then 1 else ifx code == "es" then 2 else 0\n}\n'
    for i, locale in enumerate(('en', 'de', 'es')):
        values = list(rows) if i == 0 else [row[i-1] for row in rows.values()]
        out += f'ui_{locale}: [{len(values)}]string = .[\n' + ''.join('    '+json.dumps(v, ensure_ascii=False)+',\n' for v in values) + '];\n'
    out += '''Tr :: (text: string) -> string {
    if language == 0 { return text }
    for at: cast(s32)0..cast(s32)ui_en.count - 1 {
        if text == ui_en[at] { return ifx language == 1 then ui_de[at] else ui_es[at] }
    }
    return text
}
// Stories retain one Latin-1 cell per character in the existing picture format.
// All UI, input, exported text and voice manifests use UTF-8.
LatinText :: (bytes: string) -> string {
    text: Vec(u8)
    for byte: bytes {
        if byte < cast(u8)128 { unused VecPush(text, byte) }
        else {
            unused VecPush(text, cast(u8)192 | (byte >> 6))
            unused VecPush(text, cast(u8)128 | (byte & cast(u8)63))
        }
    }
    return BuilderFinish(text)
}
'''
    (ROOT / 'retro/language.zi').write_text(out)
    print(f'Compiled {len(rows)} UI messages in three languages')
if __name__ == '__main__': main()

#!/usr/bin/env python3
"""Compile committed line-art PNGs into the portable paint masks and previews.

Transparent black pixels are background, not ink. Conservatively downsample
preview strokes so thin outlines remain visible at small sizes.
"""
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
ART = ROOT / "assets/dino-paint/art"


def ink_image(path):
    image = Image.open(path).convert("RGBA")
    ink = Image.new("1", image.size)
    for y in range(image.height):
        for x in range(image.width):
            r, g, b, a = image.getpixel((x, y))
            ink.putpixel((x, y), a >= 128 and r + g + b < 384)
    return ink


def preview(ink, width, height):
    picture = Image.new("RGBA", (width, height))
    for y in range(height):
        for x in range(width):
            left, top = x * ink.width // width, y * ink.height // height
            right = max(left + 1, (x + 1) * ink.width // width)
            bottom = max(top + 1, (y + 1) * ink.height // height)
            if ink.crop((left, top, right, bottom)).getbbox():
                picture.putpixel((x, y), (0, 0, 0, 255))
    return picture


def parts(name, number, ink):
    rows = []
    for y in range(ink.height):
        row = ""
        for x in range(0, ink.width, 4):
            value = 0
            for bit in range(4):
                if x + bit < ink.width and ink.getpixel((x + bit, y)):
                    value |= 1 << (3 - bit)
            row += format(value, "x")
        rows.append(row)
    count = (len(rows) + 2) // 3
    output = []
    for part in range(3):
        body = "\n".join(rows[part * count:(part + 1) * count]) + "\n"
        assert len(body) <= 4095
        output.append(f"{name}_{number}_{part} :: #string END\n{body}END\n\n")
    return "".join(output)


def main():
    scenes = []
    for index in range(6):
        original = ink_image(ART / f"scene{index + 1}.png")
        fitted = preview(original, 240, 180)
        scenes.append(fitted.getchannel("A").point(lambda value: 255 if value else 0, mode="1"))
    dinos = [ink_image(ART / f"dino{i + 1}-s4.png") for i in range(12)]
    code = "// Generated by tools/paint_pages.py from committed original line art.\n"
    code += "SCENE_COUNT :: 6\nDINO_COUNT :: 12\nCANVAS_WIDTH :: 240\nCANVAS_HEIGHT :: 180\n\n"
    for kind, pictures in [("SCENE", scenes), ("DINO", dinos)]:
        for index, ink in enumerate(pictures):
            code += parts(kind, index, ink)
        code += f"{kind}_PARTS :: 3\n"
    for field, values in [("WIDTH", [im.width for im in dinos]), ("HEIGHT", [im.height for im in dinos])]:
        code += f"DINO_{field}: [12]s32 = .[" + ",".join(map(str, values)) + "];\n"
    for kind, name, count in [("SCENE", "SceneLines", 6), ("DINO", "DinoLines", 12)]:
        code += f"\n{name} :: (index: s32, part: s32) -> string {{\n"
        for index in range(count):
            for part in range(3):
                code += f"    if index == {index} && part == {part} {{ return {kind}_{index}_{part} }}\n"
        code += '    return ""\n}\n'
    (ROOT / "games/paint/paint_pages.zi").write_text(code)
    for index, ink in enumerate(dinos, 1):
        fit = min(68 / ink.width, 46 / ink.height)
        preview(ink, int(ink.width * fit), int(ink.height * fit)).save(ART / f"dino{index}-thumb.png")
        for size in range(1, 5):
            fit = min(60 / ink.width, 94 / ink.height)
            preview(ink, int(ink.width * fit * size / 4), int(ink.height * fit * size / 4)).save(
                ART / f"dino{index}-preview{size}.png")
    print("Compiled alpha-aware line masks and visible dinosaur previews.")


if __name__ == "__main__":
    main()

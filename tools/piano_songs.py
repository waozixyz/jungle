"""Compile reviewed public-domain melodies into the portable piano catalog."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def table(name, values, kind='s32'):
    shown = [json.dumps(v, ensure_ascii=False) if kind == 'string' else str(v) for v in values]
    return f'{name}: [{len(values)}]{kind} = .[\n' + ',\n'.join(shown) + '];\n'


def main():
    data = json.loads((ROOT / 'tools/piano_songs.json').read_text())
    songs = data['songs']
    rows = json.loads((ROOT / 'locales/ui.json').read_text())
    output = '// Generated by tools/piano_songs.py from reviewed public-domain melodies.\n'
    output += f'PIANO_SONGS :: {len(songs)}\n'
    output += table('piano_song_titles', [s['title'][0] for s in songs], 'string')
    output += table('piano_song_verses', [s['verses'] for s in songs])
    output += table('piano_song_phrases', [len(s['phrases']) for s in songs])
    output += table('piano_song_meters', [s['meter'] for s in songs])
    output += table('piano_song_counts', [sum(map(len, s['phrases'])) for s in songs])
    for index, song in enumerate(songs):
        assert song['public_domain'] and song['source'] and song['origin']
        assert len(song['lyrics']) == song['verses'] * len(song['phrases'])
        notes, lengths, starts, counts = [], [], [], []
        for phrase in song['phrases']:
            assert 1 <= len(phrase) <= 16
            starts.append(len(notes)); counts.append(len(phrase))
            assert sum(length for _, length in phrase) % (song['meter'] * 2) == 0
            for pitch, length in phrase:
                assert data['range']['low_midi'] <= pitch <= data['range']['high_midi']
                assert pitch % 12 in (0, 2, 4, 5, 7, 9, 11), "Catalog notation currently uses natural notes"
                assert length in (1, 2, 4, 8)
                notes.append(pitch); lengths.append(length)
        output += table(f'piano_notes_{index}', notes)
        output += table(f'piano_lengths_{index}', lengths)
        output += table(f'piano_starts_{index}', starts)
        output += table(f'piano_counts_{index}', counts)
        output += table(f'piano_words_{index}', [line[0] for line in song['lyrics']], 'string')
        for translations in (song['title'], *song['lyrics']):
            # Keep the original game's already reviewed wording when present.
            rows.setdefault(translations[0], translations[1:])
    for function, prefix, kind, default in (
        ('PianoSongPitch', 'notes', 's32', '60'),
        ('PianoSongLength', 'lengths', 's32', '2'),
        ('PianoSongStart', 'starts', 's32', '0'),
        ('PianoSongCount', 'counts', 's32', '0'),
        ('PianoSongWords', 'words', 'string', '""'),
    ):
        output += f'{function} :: (song: s32, at: s32) -> {kind} {{\n'
        for index in range(len(songs)):
            output += f'    if song == {index} {{ return piano_{prefix}_{index}[at] }}\n'
        output += f'    return {default}\n}}\n'
    (ROOT / 'games/piano/catalog.zi').write_text(output)
    (ROOT / 'locales/ui.json').write_text(json.dumps(rows, ensure_ascii=False, indent=2) + '\n')
    print(f'Prepared {len(songs)} public-domain songs with fixed MIDI pitches and translated captions.')


if __name__ == '__main__':
    main()

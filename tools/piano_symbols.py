"""Extract the few engraved music symbols used by Little Piano.

Run with a local copy of Bravura.otf. Generated Ziran outlines are committed;
ordinary builds need neither the font nor fontTools. Bravura is SIL OFL 1.1:
https://github.com/steinbergmedia/bravura
"""
import hashlib
import json
from pathlib import Path
import sys

from fontTools.pens.basePen import BasePen
from fontTools.pens.boundsPen import BoundsPen
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
GLYPHS = (('CLEF', 0xE050), ('BLACK', 0xE0A4), ('HALF', 0xE0A3),
          ('TWO', 0xE082), ('FOUR', 0xE084), ('WHOLE', 0xE0A2),
          ('FLAG', 0xE240), ('FLAG_DOWN', 0xE241))


class ShapePen(BasePen):
    def __init__(self, glyphs, bounds):
        super().__init__(glyphs)
        self.x0, self.y0, x1, self.y1 = bounds
        self.factor = 22 / max(x1 - self.x0, self.y1 - self.y0)
        self.mx = (24 - (x1 - self.x0) * self.factor) / 2
        self.my = (24 - (self.y1 - self.y0) * self.factor) / 2
        self.parts = []

    def point(self, point):
        x, y = point
        return ((x - self.x0) * self.factor + self.mx,
                (self.y1 - y) * self.factor + self.my)

    def command(self, letter, points):
        self.parts.append(letter + ' '.join(f'{value:.3f}' for point in points for value in self.point(point)))

    def _moveTo(self, point):
        self.command('M', (point,))

    def _lineTo(self, point):
        self.command('L', (point,))

    def _curveToOne(self, a, b, c):
        self.command('C', (a, b, c))

    def _closePath(self):
        self.parts.append('Z')

    def _endPath(self):
        pass


def main():
    source = Path(sys.argv[1])
    font = TTFont(source)
    glyphs, cmap = font.getGlyphSet(), font.getBestCmap()
    shapes, edges, ax, ay = [], [], [], []
    output = '// Generated by tools/piano_symbols.py.\n'
    output += '// Bravura outlines: Copyright Steinberg Media Technologies GmbH, SIL OFL 1.1.\n'
    output += '// License: assets/piano/Bravura-LICENSE.txt.\n'
    output += '// Font SHA-256: ' + hashlib.sha256(source.read_bytes()).hexdigest() + '\n'
    for index, (name, code) in enumerate(GLYPHS):
        glyph = glyphs[cmap[code]]
        bounds = BoundsPen(glyphs)
        glyph.draw(bounds)
        pen = ShapePen(glyphs, bounds.bounds)
        glyph.draw(pen)
        x0, y0, x1, y1 = bounds.bounds
        # SMuFL's G clef origin is the G4 staff line. Other symbols use
        # their ink centre, so noteheads centre exactly on a line or space.
        anchor = (0, 0) if name in ('CLEF', 'FLAG', 'FLAG_DOWN') else ((x0 + x1) / 2, (y0 + y1) / 2)
        x, y = pen.point(anchor)
        shapes.append('F:' + ''.join(pen.parts))
        edges.append(24 / pen.factor / 250)
        ax.append(x / 24)
        ay.append(y / 24)
        output += f'PIANO_SYMBOL_{name} :: {index}\n'
    for (name, _), shape in zip(GLYPHS, shapes):
        output += f'PIANO_SHAPE_{name} :: ' + json.dumps(shape) + '\n'
    output += 'PianoSymbolShape :: (symbol: s32) -> string {\n'
    for index, (name, _) in enumerate(GLYPHS):
        output += f'    if symbol == {index} {{ return PIANO_SHAPE_{name} }}\n'
    output += '    return ""\n}\n'
    for name, values in (('edges', edges), ('x', ax), ('y', ay)):
        output += f'piano_symbol_{name}: [{len(GLYPHS)}]float32 = .[' + ','.join(f'{v:.6f}' for v in values) + '];\n'
    (ROOT / 'games/piano/symbols.zi').write_text(output)
    print(f'Prepared {len(GLYPHS)} engraved vector music symbols; no runtime font dependency.')


if __name__ == '__main__':
    main()

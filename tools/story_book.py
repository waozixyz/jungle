"""Compile the approved full tale separately from the word/spelling catalog."""
import json
import shutil
from web_images import prepare_runtime_images
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
CATALOG = json.loads((ROOT/'tools/canonical_avif.json').read_text())['files']

def page_geometry(rows):
    """Each page's painting sizes, paper line and paper colour, read from the
    shipped pictures: the reader lays out any story from these, so its
    pictures keep their exact aspect ratio and the caption sits on paper."""
    from PIL import Image
    from web_images import runtime_size
    sizes = {'picture_width': [], 'picture_height': [], 'portrait_width': [], 'portrait_height': [],
             'picture_runtime_width': [], 'picture_runtime_height': []}
    for row in rows:
        for kind, folder, key in (('picture', 'pages', 'asset'), ('portrait', 'portraits', 'portrait_asset')):
            name = f"assets/jungle-book/{folder}/{row[key]}.avif"
            with Image.open(ROOT/name) as image:
                # Layout and the paper line use the painting's design size; the
                # shipped copy may be its 75% Lanczos export (canonical_avif.json).
                design = CATALOG.get(name, {}).get('design_dimensions', image.size)
                sizes[kind+'_width'].append(design[0])
                sizes[kind+'_height'].append(design[1])
                if kind == 'picture':
                    # Hosts crop the landscape picture's runtime copy, which
                    # can be smaller than the painting.
                    width, height = runtime_size(name, image.size)
                    sizes['picture_runtime_width'].append(width)
                    sizes['picture_runtime_height'].append(height)
    for row, height in zip(rows, sizes['picture_height']):
        assert 0 < row['paper_top'] < height, row['asset']
        assert len(row['paper_color']) == 7 and row['paper_color'][0] == '#', row['asset']
    colors = [int(row['paper_color'][1:], 16) << 8 | 0xff for row in rows]
    return [(name, values, 's32') for name, values in sizes.items()] + [
        ('paper_top', [row['paper_top'] for row in rows], 's32'), ('paper_color', colors, 'u32')]

def literal(value, kind):
    return f'0x{value:08x}' if kind == 'u32' else json.dumps(value, ensure_ascii=False)

def main(export_art=False):
    story = json.loads((ROOT/'tools/sweet_porridge.json').read_text())
    rows=story['pages']
    if export_art:
        # Export exact approved masters through the shared runtime encoder once;
        # staging reuses these compact AVIF bytes on native, web and Android.
        masters = ROOT/'local/art-development/sweet-porridge-portrait'
        sources = {f"assets/jungle-book/portraits/{row['portrait_asset']}.png":
                   masters/(row['portrait_asset']+'.png') for row in rows}
        exports = prepare_runtime_images(sources, ROOT/'work/porridge-portrait-integration/exports')
        for name, export in exports.items():
            target = (ROOT/name).with_suffix('.avif')
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(export.source, target)
    out = '// Generated by tools/story_book.py; cover plus ten complete story pages.\n'
    out += f'STORY_PAGE_COUNT :: {len(rows)}\n'
    def array(name,values,kind='string'):
        nonlocal out
        out += f'{name}: [{len(values)}]{kind} = .[' + ', '.join(literal(v,kind) for v in values) + '];\n'
    array('story_pictures',[f"assets/jungle-book/pages/{r['asset']}.avif" for r in rows])
    array('story_portraits',[f"assets/jungle-book/portraits/{r['portrait_asset']}.avif" for r in rows])
    for name,values,kind in page_geometry(rows):
        array('story_'+name,values,kind)
    for lang in ('en','de','es'):
        array('story_caption_'+lang,[r[lang] for r in rows])
        paths=[f"assets/jungle-book/story-sounds/{lang}/{r['asset']}.wav" for r in rows]
        array('story_voice_'+lang,paths)
        receipts=[json.loads((ROOT/p).with_suffix('.speech.json').read_text()) for p in paths]
        assert all(r['text']==page[lang] for r,page in zip(receipts,rows))
        array('story_seconds_'+lang,[r['duration'] for r in receipts],'float64')
    for name,kind,stem in [('Caption','string','caption'),('Voice','string','voice'),('Seconds','float64','seconds')]:
        out += f'Story{name} :: (page: s32, language: s32) -> {kind} {{\n    if language == 1 {{ return story_{stem}_de[page] }}\n    if language == 2 {{ return story_{stem}_es[page] }}\n    return story_{stem}_en[page]\n}}\n'
    (ROOT/'games/book/sweet_porridge.zi').write_text(out)
    print('Compiled complete story: 11 pages, EN/DE/ES captions and measured narration')
if __name__=='__main__':
    import argparse
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--export-art', action='store_true', help='explicitly export approved local originals')
    main(export_art=parser.parse_args().export_art)

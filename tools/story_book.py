"""Compile the approved full tale separately from the word/spelling catalog."""
import json
import shutil
from web_images import prepare_runtime_images
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
def main(export_art=False):
    story = json.loads((ROOT/'tools/sweet_porridge.json').read_text())
    rows=story['pages']
    if export_art:
        # Export exact approved masters through the shared runtime encoder once;
        # staging reuses these compact WebP bytes on native, web and Android.
        masters = ROOT/'local/art-development/sweet-porridge-portrait'
        sources = {f"assets/jungle-book/portraits/{row['portrait_asset']}.png":
                   masters/(row['portrait_asset']+'.png') for row in rows}
        exports = prepare_runtime_images(sources, ROOT/'work/porridge-portrait-integration/exports')
        for name, export in exports.items():
            target = (ROOT/name).with_suffix('.webp')
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(export.source, target)
    out = '// Generated by tools/story_book.py; cover plus ten complete story pages.\n'
    out += f'STORY_PAGE_COUNT :: {len(rows)}\n'
    def array(name,values,kind='string'):
        nonlocal out
        out += f'{name}: [{len(values)}]{kind} = .[' + ', '.join(json.dumps(v,ensure_ascii=False) for v in values) + '];\n'
    array('story_pictures',[f"assets/jungle-book/pages/{r['asset']}.webp" for r in rows])
    array('story_portraits',[f"assets/jungle-book/portraits/{r['portrait_asset']}.webp" for r in rows])
    array('story_paper_top',[r['paper_top'] for r in rows],'s32')
    for lang in ('en','de','es'):
        array('story_caption_'+lang,[r[lang] for r in rows])
        paths=[f"assets/jungle-book/story-sounds/{lang}/{r['asset']}.wav" for r in rows]
        array('story_voice_'+lang,paths)
        receipts=[json.loads((ROOT/p).with_suffix('.speech.json').read_text()) for p in paths]
        assert all(r['text']==page[lang] for r,page in zip(receipts,rows))
        array('story_seconds_'+lang,[r['duration'] for r in receipts],'float64')
    for name,kind,stem in [('Caption','string','caption'),('Voice','string','voice'),('Seconds','float64','seconds')]:
        out += f'Story{name} :: (page: s32, language: s32) -> {kind} {{\n    if language == 1 {{ return story_{stem}_de[page] }}\n    if language == 2 {{ return story_{stem}_es[page] }}\n    return story_{stem}_en[page]\n}}\n'
    (ROOT/'games/book/sweet_porridge.zi').write_text(out)
    print('Compiled complete story: 11 pages, EN/DE/ES captions and measured narration')
if __name__=='__main__':
    import argparse
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--export-art', action='store_true', help='explicitly export approved local originals')
    main(export_art=parser.parse_args().export_art)

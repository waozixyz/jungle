#!/usr/bin/env python3
"""Validate and compile reusable title animation atlases; runtime needs no masters."""
import argparse
import json
from pathlib import Path
from PIL import Image
ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT/'tools/title_animations.json'
TARGET = ROOT/'host/jungle_title_animation_data.zi'

def generate():
    layers = json.loads(SOURCE.read_text())['layers']
    fields = {'SCENE': ('string', []), 'PATH': ('string', []), 'SHEET': ('s32', []),
              'RECT': ('float32', []), 'TIMING': ('float64', []), 'MODE': ('s32', [])}
    for layer in layers:
        path = ROOT/layer['path']
        assert path.suffix == '.webp', path
        columns, count, width, height = layer['sheet']
        assert 0 < count <= columns and width > 0 and height > 0
        with Image.open(path) as im:
            assert im.size == (columns*width, height), (path, im.size)
        assert layer['timing'][0] > 0 and layer['timing'][1] > 0
        assert layer['mode'] in (0, 1, 2)
        for key, value in [('SCENE',layer['scene']), ('PATH',layer['path']),
                           ('SHEET',layer['sheet']), ('RECT',layer['rect']),
                           ('TIMING',layer['timing']), ('MODE',layer['mode'])]:
            fields[key][1].extend(value if isinstance(value,list) else [value])
    out = ['// Generated by tools/title_animations.py; edit tools/title_animations.json.',
           f'TITLE_ANIMATION_COUNT :: {len(layers)};']
    for name,(kind,values) in fields.items():
        literals = [json.dumps(v) if kind=='string' else str(float(v)) if kind.startswith('float') else str(v) for v in values]
        out.append(f'TITLE_ANIMATION_{name}: [{len(values)}]{kind} = .[\n    '+',\n    '.join(literals)+'\n];')
    return '\n\n'.join(out)+'\n'

def main():
    parser=argparse.ArgumentParser(); parser.add_argument('--check',action='store_true'); args=parser.parse_args()
    text=generate()
    if args.check:
        assert TARGET.read_text()==text, 'Run python3 tools/title_animations.py'
    else: TARGET.write_text(text)
if __name__=='__main__': main()

#!/usr/bin/env python3
"""The toucan's daily gifts: its carrying poses, the carried items, the
treasures and the chest (host/jungle_treasure.zi, host/jungle_toucan.zi).

Every picture is its own trimmed transparent cut-out from a private PNG master
in local/art-development/toucan-reward/, shipped under the 75% AVIF standard
(tools/image_exports.py) and drawn into a layout rectangle, never baked into a
scene. Poses are placed in pixels of the toucan's window-animation atlas frame:
BOX is where the pose's picture covers that frame and HOLD the beak's anchor
and the carried item's largest side.

  tools/toucan_reward_art.py           export changed masters, regenerate code
  tools/toucan_reward_art.py --check   verify shipped files and generated code
"""
import argparse
import json
from pathlib import Path
import sys

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'tools'))
SOURCE = ROOT / 'tools/toucan_reward_art.json'
ANIMATIONS = ROOT / 'tools/title_animations.json'
GENERATED = ROOT / 'host/jungle_toucan_poses.zi'
TRIMMED = ROOT / 'local/art-development/toucan-reward/trimmed'
# Largest on-screen side: the chest view and the gift card stay under this.
MAX_DISPLAY = 512
PADDING = 6


def frame_width(animal):
    for layer in json.loads(ANIMATIONS.read_text())['layers']:
        if layer['path'] == animal:
            return layer['sheet'][2]
    raise ValueError(f'{animal} is not a title animation')


def render(source):
    """host/jungle_toucan_poses.zi for SOURCE's poses."""
    poses = source['poses']
    names, paths, units, boxes, holds = [], [], [], [], []
    for pose in poses:
        x, y, w, h = pose['box']
        hx, hy, size = pose['hold']
        if pose['name'] in names or w <= 0 or h <= 0 or size <= 0 or not (x <= hx <= x + w and y <= hy <= y + h):
            raise ValueError(f'bad pose {pose}')
        names.append(pose['name']); paths.append(pose['path']); units.append(frame_width(pose['animal']))
        boxes.extend(pose['box']); holds.extend(pose['hold'])
    out = ['// Generated by tools/toucan_reward_art.py; edit tools/toucan_reward_art.json.',
           f'TOUCAN_POSE_COUNT :: {len(poses)};']
    if not poses:
        # Until the poses ship the toucan stays an ordinary visitor.
        names, paths, units, boxes, holds = [''], [''], [1.0], [0, 0, 1, 1], [0, 0, 1]
    for name, kind, values in (('NAME', 'string', names), ('PATH', 'string', paths), ('UNIT', 'float32', units),
                               ('BOX', 'float32', boxes), ('HOLD', 'float32', holds)):
        literals = [json.dumps(v) if kind == 'string' else str(float(v)) for v in values]
        out.append(f'TOUCAN_POSE_{name}: [{len(values)}]{kind} = .[\n    ' + ',\n    '.join(literals) + '\n];')
    return '\n'.join(out) + '\n'


def pictures(source):
    return [(entry['master'], entry['path']) for entry in source['items'] + source['poses']]


def check(source):
    """Every shipped picture exists, is a trimmed RGBA AVIF with a receipt row,
    each pose keeps its box's shape, and the generated code is current."""
    receipt = json.loads((ROOT / 'tools/canonical_avif.json').read_text())['files']
    for _, path in pictures(source):
        shipped = ROOT / path
        with Image.open(shipped) as picture:
            assert picture.format == 'AVIF' and picture.mode == 'RGBA', (path, 'needs a transparent AVIF')
            box = picture.getchannel('A').point(lambda a: 255 if a > 8 else 0).getbbox()
            assert box, (path, 'empty cut-out')
            margins = (box[0], box[1], picture.width - box[2], picture.height - box[3])
            assert max(margins) <= PADDING, (path, 'transparent padding', margins)
            assert max(picture.size) <= 2 * MAX_DISPLAY, (path, 'oversized', picture.size)
            size = picture.size
        assert path in receipt, (path, 'missing from tools/canonical_avif.json')
        for pose in source['poses']:
            if pose['path'] == path:
                w, h = pose['box'][2:]
                assert abs(size[0] / size[1] - w / h) < 0.02 * (w / h), (path, 'box keeps the pose aspect')
    assert GENERATED.read_text() == render(source), 'host/jungle_toucan_poses.zi is stale: run tools/toucan_reward_art.py'


def export(source, only=(), pending=None):
    from image_exports import export_scaled_master, record_canonical_rows, trim_cutout
    rows = {}
    TRIMMED.mkdir(parents=True, exist_ok=True)
    for master, path in pictures(source):
        if only and Path(path).stem not in only:
            continue
        with Image.open(ROOT / master) as original:
            picture, _ = trim_cutout(original, MAX_DISPLAY, margin=2)
        frame = next((pose['frame'] for pose in source['poses'] if pose['path'] == path), None)
        if frame:
            # FRAME maps the master into the atlas frame: master = offset + frame pixel * scale.
            with Image.open(ROOT / master) as original:
                _, crop = trim_cutout(original, MAX_DISPLAY, margin=2)
            ox, oy, scale = frame
            pose = next(pose for pose in source['poses'] if pose['path'] == path)
            pose['box'] = [round((crop[0] - ox) / scale, 2), round((crop[1] - oy) / scale, 2),
                           round((crop[2] - crop[0]) / scale, 2), round((crop[3] - crop[1]) / scale, 2)]
        trimmed = TRIMMED / (Path(path).stem + '.png')
        picture.save(trimmed)
        (ROOT / path).parent.mkdir(parents=True, exist_ok=True)
        rows[path] = export_scaled_master(trimmed, ROOT / path)
        print(path, rows[path]['dimensions'], rows[path]['bytes'], 'bytes')
    if rows and pending:
        # Receipt rows held aside while another change owns the receipt.
        held = json.loads(pending.read_text()) if pending.exists() else {}
        held.update(rows)
        pending.write_text(json.dumps(held, indent=2, ensure_ascii=False) + '\n')
    elif rows:
        record_canonical_rows(rows)
    SOURCE.write_text(json.dumps(source, indent=2, ensure_ascii=False) + '\n')
    GENERATED.write_text(render(source))


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--pending', type=Path, help='hold receipt rows in this JSON instead')
    parser.add_argument('only', nargs='*', help='shipped names (without .avif) to export')
    options = parser.parse_args()
    source = json.loads(SOURCE.read_text())
    if options.check:
        check(source)
        print('toucan reward art ok')
    else:
        export(source, set(options.only), options.pending)


if __name__ == '__main__':
    main()

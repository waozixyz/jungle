"""Export the finished Bremen paintings and compile the shared reader data."""
import hashlib
import json
from pathlib import Path
from image_exports import export_image, optimize_new_image_exports
from story_book import page_geometry, literal
import shutil
ROOT = Path(__file__).resolve().parents[1]

def main(export=False, landscape=False):
    story = json.loads((ROOT/'tools/town_musicians.json').read_text())
    rows = story['pages']
    if export:
        mapping = json.loads((ROOT/'local/art-development/town-musicians-portrait/mapping.json').read_text())
        mapping['status'] = 'Integrated at explicit owner request; existing finished pictures'
        for row, scene in zip(rows, mapping['scenes']):
            source = ROOT/'local/art-development/town-musicians-portrait'/scene['portrait']
            assert hashlib.sha256(source.read_bytes()).hexdigest() == scene['portrait_sha256']
            target = ROOT/f"assets/jungle-book/portraits/{row['asset']}.avif"
            export_image(source, target, 'book-page')
            scene.update(status='Integrated at explicit owner request', runtime=str(target.relative_to(ROOT)), runtime_sha256=hashlib.sha256(target.read_bytes()).hexdigest())
        target = ROOT/'tools/art_provenance/town-musicians-portrait/mapping.json'
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(json.dumps(mapping, ensure_ascii=False, indent=2)+'\n')
    if landscape:
        base = ROOT/'local/art-development/town-musicians-landscape'
        mapping = json.loads((base/'mapping.json').read_text())
        for scene in mapping['scenes']:
            source = ROOT/scene['source']
            assert hashlib.sha256(source.read_bytes()).hexdigest() == scene['source_sha256']
            result = optimize_new_image_exports(source, 'book-page', base/'exports')
            target = ROOT/scene['runtime']
            shutil.copyfile(result.source, target)
            scene['runtime_sha256'] = hashlib.sha256(target.read_bytes()).hexdigest()
        (ROOT/'tools/art_provenance/town-musicians-landscape/mapping.json').write_text(json.dumps(mapping, indent=2)+'\n')
    out = '// Generated by tools/town_musicians_book.py.\n'
    out += f'BREMEN_PAGE_COUNT :: {len(rows)}\n'
    def array(name, values, kind='string'):
        nonlocal out
        out += f"bremen_{name}: [{len(values)}]{kind} = .[" + ', '.join(literal(v,kind) for v in values) + '];\n'
    array('pictures', [f"assets/jungle-book/pages/{r['asset']}.avif" for r in rows])
    array('portraits', [f"assets/jungle-book/portraits/{r['portrait_asset']}.avif" for r in rows])
    for name, values, kind in page_geometry(rows):
        array(name, values, kind)
    for lang in ('en','de','es'):
        array('caption_'+lang, [r[lang] for r in rows])
        paths = [f"assets/jungle-book/story-sounds/{lang}/{r['asset']}.wav" for r in rows]
        receipts = [json.loads((ROOT/p).with_suffix('.speech.json').read_text()) for p in paths]
        assert all(r['text']==page[lang] for r,page in zip(receipts,rows))
        array('voice_'+lang, paths)
        array('seconds_'+lang, [r['duration'] for r in receipts], 'float64')
    for name,kind in [('Caption','string'),('Voice','string'),('Seconds','float64')]:
        out += f'Bremen{name} :: (page: s32, language: s32) -> {kind} {{\n    if language == 1 {{ return bremen_{name.lower()}_de[page] }}\n    if language == 2 {{ return bremen_{name.lower()}_es[page] }}\n    return bremen_{name.lower()}_en[page]\n}}\n'
    (ROOT/'games/book/town_musicians.zi').write_text(out)
if __name__ == '__main__':
    import sys
    main('--export-art' in sys.argv, '--export-landscape-art' in sys.argv)
